//! Text helpers of the material rules: accent-free lowercase and keyword search.

/// `text` in lowercase without accents, so `Cerámica`, `ceramica` and `CERAMICA` compare equal.
pub fn fold(text: &str) -> String {
    text.chars()
        .flat_map(char::to_lowercase)
        .map(|c| match c {
            'á' | 'à' | 'ä' | 'â' => 'a',
            'é' | 'è' | 'ë' | 'ê' => 'e',
            'í' | 'ì' | 'ï' | 'î' => 'i',
            'ó' | 'ò' | 'ö' | 'ô' => 'o',
            'ú' | 'ù' | 'ü' | 'û' => 'u',
            'ñ' => 'n',
            other => other,
        })
        .collect()
}

/// Whether the folded `text` contains any of `words`.
pub fn has(text: &str, words: &[&str]) -> bool {
    words.iter().any(|word| text.contains(word))
}

/// How far apart the strongest and weakest channel of `rgb` are (0 is a pure gray).
pub fn saturation(rgb: [f32; 3]) -> f32 {
    let max = rgb[0].max(rgb[1]).max(rgb[2]);
    let min = rgb[0].min(rgb[1]).min(rgb[2]);
    max - min
}

/// Linear mix of two colors.
pub fn mix(a: [f32; 3], b: [f32; 3], t: f32) -> [f32; 3] {
    std::array::from_fn(|i| a[i] + (b[i] - a[i]) * t)
}
